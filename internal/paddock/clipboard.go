const maxClipboardImage = 20 << 20

var clipboardName = regexp.MustCompile(`^(?:rex-clipboard-[A-Fa-f0-9-]{36}|codex-clipboard-[A-Za-z0-9_-]+)\.(?:png|jpg|jpeg|gif|webp)$`)
var clipboardImageEnd = regexp.MustCompile(`\.(?:png|jpg|jpeg|gif|webp)`)

func clipboardDirectories() []string {
	dirs := []string{filepath.Clean(os.TempDir())}
	if canonical, err := filepath.EvalSymlinks(dirs[0]); err == nil && canonical != dirs[0] {
		dirs = append(dirs, canonical)
	}
	// macOS tools use both spellings for its per-user temporary directory.
	for _, dir := range append([]string{}, dirs...) {
		if strings.HasPrefix(dir, "/private/var/") {
			dirs = append(dirs, strings.TrimPrefix(dir, "/private"))
		}
	}
	return dirs
}

// clipboardInput preserves the terminal byte stream, including bracketed-paste
// markers. Only complete image paths generated by Rex/Codex in this user's
// temporary directory are rewritten. It tolerates arbitrary read boundaries.
type clipboardInput struct {
	out      io.Writer
	prefixes []string
	pending  []byte
	upload   func(string) (string, error)
}

func newClipboardInput(out io.Writer, dirs []string, upload func(string) (string, error)) *clipboardInput {
	f := &clipboardInput{out: out, upload: upload}
	for _, dir := range dirs {
		for _, name := range []string{"rex-clipboard-", "codex-clipboard-"} {
			f.prefixes = append(f.prefixes, filepath.Join(dir, name))
		}
	}
	return f
}

func (f *clipboardInput) emit(data []byte) error {
	_, err := f.out.Write(data)
	return err
}

func (f *clipboardInput) Write(data []byte) (int, error) {
	f.pending = append(f.pending, data...)
	for len(f.pending) > 0 {
		start := -1
		matchedPrefix := ""
		for _, prefix := range f.prefixes {
			if i := bytes.Index(f.pending, []byte(prefix)); i >= 0 && (start < 0 || i < start) {
				start = i
				matchedPrefix = prefix
			}
		}
		if start < 0 {
			keep := 0
			for _, prefix := range f.prefixes {
				for n := min(len(prefix)-1, len(f.pending)); n > keep; n-- {
					if bytes.Equal(f.pending[len(f.pending)-n:], []byte(prefix[:n])) {
						keep = n
						break
					}
				}
			}
			if err := f.emit(f.pending[:len(f.pending)-keep]); err != nil {
				return 0, err
			}
			f.pending = append(f.pending[:0], f.pending[len(f.pending)-keep:]...)
			break
		}
		if err := f.emit(f.pending[:start]); err != nil {
			return 0, err
		}
		f.pending = f.pending[start:]
		// Clipboard basenames contain no spaces, slashes, or terminal controls.
		base := bytes.LastIndexByte([]byte(matchedPrefix), '/') + 1
		end := clipboardImageEnd.FindIndex(f.pending[base:])
		if end != nil {
			n := base + end[1]
			name := string(f.pending[:n])
			if clipboardName.MatchString(filepath.Base(name)) {
				destination, err := f.upload(name)
				if err != nil {
					destination = "[Paddock could not transfer the pasted image: " + err.Error() + ". Paste the image again to retry.]"
				}
				if err = f.emit([]byte(destination)); err != nil {
					return 0, err
				}
				f.pending = f.pending[n:]
				continue
			}
		}
		possible := len(f.pending) < 1024
		for _, char := range f.pending[base:] {
			if !(char >= 'a' && char <= 'z' || char >= 'A' && char <= 'Z' || char >= '0' && char <= '9' || char == '-' || char == '_' || char == '.') {
				possible = false
				break
			}
		}
		if possible {
			break
		}
		if err := f.emit(f.pending[:1]); err != nil {
			return 0, err
		}
		f.pending = f.pending[1:]
	}
	return len(data), nil
}

func (f *clipboardInput) Flush() error {
	err := f.emit(f.pending)
	f.pending = nil
	return err
}

func snapshotClipboardImage(source string, dirs []string) (string, string, func(), error) {
	noop := func() {}
	if !clipboardName.MatchString(filepath.Base(source)) {
		return "", "", noop, fmt.Errorf("unrecognized clipboard image")
	}
	parent, err := filepath.EvalSymlinks(filepath.Dir(source))
	if err != nil {
		return "", "", noop, fmt.Errorf("clipboard image is unavailable")
	}
	allowed := false
	for _, dir := range dirs {
		canonical, err := filepath.EvalSymlinks(dir)
		if err == nil && parent == canonical {
			allowed = true
			break
		}
	}
	if !allowed {
		return "", "", noop, fmt.Errorf("image is outside the clipboard directory")
	}
	file, err := openClipboardImage(source)
	if err != nil {
		return "", "", noop, fmt.Errorf("clipboard image is unavailable or is a link")
	}
	defer file.Close()
	info, err := file.Stat()
	if err != nil || !info.Mode().IsRegular() {
		return "", "", noop, fmt.Errorf("clipboard image is not a regular file")
	}
	if info.Size() > maxClipboardImage {
		return "", "", noop, fmt.Errorf("image exceeds the 20 MiB limit")
	}
	data, err := io.ReadAll(io.LimitReader(file, maxClipboardImage+1))
	if err != nil || len(data) > maxClipboardImage {
		return "", "", noop, fmt.Errorf("image could not be read within the 20 MiB limit")
	}
	typeOf := http.DetectContentType(data)
	extensions := map[string]string{"image/png": ".png", "image/jpeg": ".jpg", "image/gif": ".gif", "image/webp": ".webp"}
	ext, ok := extensions[typeOf]
	if !ok {
		return "", "", noop, fmt.Errorf("clipboard file is not a supported image")
	}
	dir, err := os.MkdirTemp("", "paddock-clipboard-")
	if err != nil {
		return "", "", noop, fmt.Errorf("could not stage the clipboard image")
	}
	cleanup := func() { _ = os.RemoveAll(dir) }
	hash := sha256.Sum256(data)
	name := hex.EncodeToString(hash[:]) + ext
	staged := filepath.Join(dir, name)
	if err = os.WriteFile(staged, data, 0600); err != nil {
		cleanup()
		return "", "", noop, fmt.Errorf("could not stage the clipboard image")
	}
	return staged, "/sandbox/.paddock/attachments/" + name, cleanup, nil
}

func uploadClipboardImage(ctx context.Context, task Task, source string) (string, error) {
	staged, destination, cleanup, err := snapshotClipboardImage(source, clipboardDirectories())
	if err != nil {
		return "", err
	}
	defer cleanup()
	ctx, cancel := context.WithTimeout(ctx, 30*time.Second)
	defer cancel()
	if _, err = sandboxOutput(ctx, task, "/bin/mkdir", "-p", "/sandbox/.paddock/attachments"); err != nil {
		return "", fmt.Errorf("sandbox attachment directory is unavailable")
	}
	if _, err = task.OpenShell.Config.call(ctx, "sandbox", "upload", task.OpenShell.Name, staged, destination); err != nil {
		return "", fmt.Errorf("sandbox upload failed")
	}
	return destination, nil
}

func wrapClipboardCommand(task Task, home, executable string, command *exec.Cmd) error {
	if task.RuntimeName() != "openshell" || !clipboardTerminal() {
		return nil
	}
	proxy, err := sandboxAgentProxy(home, executable, task.Session.Agent)
	if err != nil {
		return err
	}
	command.Path = proxy
	command.Args = []string{task.Session.Agent, "__paste", task.ID, "--generation", fmt.Sprint(task.Session.Generation)}
	if task.Session.ResumeNotice != "" {
		command.Args = append(command.Args, "--resume-notice", task.Session.ResumeNotice)
	}
	command.Env = append(command.Env, "PADDOCK_HOME="+home)
	return nil
}

func pasteAgentCommand(store *Store, id string, generation int, resumeNotice string) (Task, *exec.Cmd, error) {
	task, err := store.Get(id)
	if err == nil && (task.RuntimeName() != "openshell" || task.OpenShell == nil || task.Session.Generation != generation || task.Status != "running") {
		err = fmt.Errorf("invalid or stale sandbox paste transport")
	}
	if err != nil {
		return task, nil, err
	}
	// The supervisor clears this durable marker when it claims the generation.
	// Carry its launch-time copy through the helper so recovery still warns the
	// resumed conversation that uncommitted files and build state were lost.
	task.Session.ResumeNotice = resumeNotice
	return task, AgentCommand(task, store.Home, ""), nil
}

func RunPasteAgent(store *Store, id string, generation int, resumeNotice string) int {
	task, command, err := pasteAgentCommand(store, id, generation, resumeNotice)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	code, err := runPasteTerminal(ctx, command, func(ctx context.Context, source string) (string, error) {
		return uploadClipboardImage(ctx, task, source)
	})
	if err != nil {
		fmt.Fprintln(os.Stderr, "Paddock image paste:", err)
	}
	return code
}
